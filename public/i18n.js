export const STRINGS = { en, ko };

let current = 'en';
export const language = () => current;
// Anything but a known language reads as English.
export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'en';
  return current;
}
// The language named by "?lang=" in an address (the rack panel's kiosk has no keyboard to pick one).
export function queryLanguage(search = '') {
  const value = new URLSearchParams(search).get('lang');
  return LANGUAGES.includes(value) ? value : 'en';
}
// The locale for dates and times written out by the browser (the 12-hour clock's AM and PM).
export const locale = (lang = current) => (lang === 'ko' ? 'ko-KR' : 'en-US');

export function t(key, params = {}, lang = current) {
  let text = STRINGS[lang]?.[key] ?? en[key] ?? key;
  if (Array.isArray(text)) text = text[params?.count === 1 ? 0 : 1];
  return text.replace(/\{(\w+)\}/g, (match, name) => {
    if (!params || !Object.hasOwn(params, name)) return match;
    const value = params[name];
    return Array.isArray(value) ? value.join(', ') : String(value);
  });
}

// Whether the language's own table has the key (t() would otherwise fall back to English).
export const hasOwnString = (key, lang = current) => Object.hasOwn(STRINGS[lang] ?? {}, key);

// A status message from the server in the page's language: the text for its messageKey, or the server's own English
// message when the page is in English, the key is unknown (a newer server) or there is none (an older one).
export function serverText(key, params, message, lang = current) {
  if (lang === 'en' || typeof key !== 'string' || !hasOwnString(key, lang)) return message;
  return t(key, params ?? {}, lang);
}

// The page's fixed text: data-i18n sets an element's text, data-i18n-title and data-i18n-aria-label its attributes.
export function translatePage(root = document) {
  document.documentElement.lang = current;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
}
